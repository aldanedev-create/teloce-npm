"""
Wrap IIFE (Immediately Invoked Function Expression) packages for the browser.
"""

from teloce_npm.utils.logging import logger

from .base import BaseWrapper


class LifeWrapper(BaseWrapper):

    def wrap(self) -> str:
        entry_path = self._find_entry_file()
        logger.debug(f"Wrapping IIFE entry: {entry_path}")

        source_code = entry_path.read_text(encoding="utf-8")

        window_name = self._window_name()

        # IIFE packages usually attach to `window` directly.
        # We just wrap them in a safety closure.
        return f"""
// ============================================================
// Wrapped IIFE package: {self.package_name}
// Generated by Teloce-NPM
// ============================================================
(function() {{
    // ---- Original package code ----
    {source_code}
    // ---- End original package code ----

    // If the package didn't attach itself, try to find it
    if (typeof window['{window_name}'] === 'undefined') {{
        console.warn('[Teloce-NPM] Package "{self.package_name}" did not attach to window.');
    }}
}})();
"""
