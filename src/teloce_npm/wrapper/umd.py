"""
Wrap UMD (Universal Module Definition) packages for the browser.
"""

from pathlib import Path

from .base import BaseWrapper
from teloce_npm.utils.logging import logger

class UmdWrapper(BaseWrapper):

    def wrap(self) -> str:
        entry_path = self._find_entry_file()
        logger.debug(f"Wrapping UMD entry: {entry_path}")
        
        source_code = entry_path.read_text(encoding="utf-8")

        window_name = self._window_name()

        # UMD packages already check for `module.exports` and `define`.
        # By providing a fake `module` object, we force them to take the CommonJS path,
        # then we attach that to window.
        return f"""
// ============================================================
// Wrapped UMD package: {self.package_name}
// Generated by Teloce-NPM
// ============================================================
(function() {{
    var module = {{ exports: {{}} }};
    var exports = module.exports;

    // ---- Original package code ----
    {source_code}
    // ---- End original package code ----

    // UMD packages usually attach to `this` or `window` directly,
    // but if they took the CommonJS path, attach module.exports.
    if (module.exports && Object.keys(module.exports).length > 0) {{
        window['{window_name}'] = module.exports;
    }}
}})();
"""